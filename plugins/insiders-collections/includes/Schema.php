	public static function install(): array {
		global $wpdb;
		$report  = array();
		$charset = $wpdb->get_charset_collate();
		foreach ( self::tables() as $name => $columns ) {
			$table = Db::t( $name );
			$sql   = "CREATE TABLE IF NOT EXISTS `{$table}` ( {$columns} ) ENGINE=InnoDB {$charset}";
			$ok    = $wpdb->query( $sql );
			$report[ $name ] = ( false === $ok ) ? 'error: ' . $wpdb->last_error : 'ok';
		}
		update_option( 'icol_db_version', ICOL_DB_VERSION, false );
		return $report;
	}

	/** Verifies every table exists and is InnoDB (transactions + row locks depend on it). */
	public static function verify(): array {
		global $wpdb;
		$out = array();
		foreach ( array_keys( self::tables() ) as $name ) {
			$table = Db::t( $name );
			$row   = $wpdb->get_row(
				$wpdb->prepare( 'SELECT ENGINE FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = %s', $table ),
				ARRAY_A
			);
			$out[ $name ] = $row ? ( 'InnoDB' === $row['ENGINE'] ? 'ok' : 'engine=' . $row['ENGINE'] ) : 'missing';
		}
		return $out;
	}

	/** For future migrations: explicit, idempotent ALTER after an information_schema check. */
	public static function ensure_column( string $name, string $column, string $definition ): bool {
		global $wpdb;
		$table  = Db::t( $name );
		$exists = $wpdb->get_var(
			$wpdb->prepare( 'SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = %s AND COLUMN_NAME = %s', $table, $column )
		);
		if ( (int) $exists > 0 ) {
			return true;
		}
		return false !== $wpdb->query( "ALTER TABLE `{$table}` ADD COLUMN `{$column}` {$definition}" );
	}
