/**
 * Custom tables, created with explicit SQL and checked through information_schema.
 *
 * Why not user_meta (the house default): the ledger needs UNIQUE constraints and
 * row locks to guarantee "one payment, one allocation" under concurrent webhooks.
 * Why not dbDelta: it reports nothing when it skips an index or a column, and
 * it broke a site once. Every statement here is idempotent.
 *
 * DATETIME columns are NULL-able and written from PHP in UTC; DEFAULT
 * CURRENT_TIMESTAMP fails on older MariaDB.
 */
